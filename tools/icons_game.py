def splat(light, mid, dark):
    """A blob of dirt in three shades; each dirt type gets one in its own colours."""
    g = """
................
.....KK...K.....
....KmmK.KmK....
...KmmmmKmmmK...
..KmmllmmmmmmK..
..KmlllmmmmddK..
.KmmllmmmmmdddK.
.KmmmmmmmmmddK..
.KmmmmmmmmdddK..
..KmmmmmmmdddK..
..KKmmmmmddddK..
..KmKmmmdddKK...
.KmK.KmddddK....
.KK...KKdKK.....
.......KK.......
................
"""
    return g.replace('l', light).replace('m', mid).replace('d', dark)

