def build():
    out = {}
    for n, g in base.ICONS.items(): out[n] = base.svg(g, 16)
    for n, g in extra.EXTRA.items(): out[n] = base.svg(g, 16)
    for n, g in GAME.items(): out[n] = base.svg(g, 16)
    for n, g in base.LOGOS.items(): out[n] = base.svg(g, 24)
    for n, g in extra.PORTRAITS.items(): out['p_' + n] = base.svg(g, 24)
    # strip fixed width/height so CSS sizes them
    for k, v in out.items(): out[k] = v.replace(' width="16" height="16"', '').replace(' width="24" height="24"', '')
    return out

if __name__ == '__main__':
    out = build()
    dest = os.path.join(os.path.dirname(__file__), '..', 'src', 'icons.json')
    json.dump(out, open(dest, 'w'))
    print(len(out), 'icons ->', os.path.relpath(dest))
    if '--sheet' in sys.argv:
        sheet = '<html><body style="background:#8fcbe4;padding:20px;display:flex;flex-wrap:wrap;gap:16px">'
        for n in out:
            big = out[n].replace('<svg ', '<svg style="width:64px;height:64px;image-rendering:pixelated" ')
            sheet += '<div style="text-align:center;font:12px monospace"><div style="width:64px;height:64px">' + big + '</div>' + n + '</div>'
        path = os.path.join(os.path.dirname(__file__), 'icon-sheet.html')
        open(path, 'w').write(sheet + '</body></html>')
        print('sheet ->', os.path.relpath(path))
